// Builds js/dist/kraken-decode.mjs: the loader with the WebAssembly module
// embedded as base64, so a bundler (or `import`) needs one file and no fetch.
//
//   cargo build -p kraken-decode-wasm --target wasm32-unknown-unknown --release
//   node js/build.mjs

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const wasm = readFileSync(new URL("target/wasm32-unknown-unknown/release/kraken_decode_wasm.wasm", root));
const loader = readFileSync(new URL("js/src/loader.mjs", root), "utf8");
const version = /^version = "(.+)"$/m.exec(readFileSync(new URL("Cargo.toml", root), "utf8"))[1];

const out = `// kraken-decode ${version} (MIT, https://github.com/MaddisonM79/kraken-decode). Generated by js/build.mjs: do not edit.
${loader}
const WASM_BASE64 = "${wasm.toString("base64")}";
const decodeBase64 = (text) => (typeof Buffer === "function" ? new Uint8Array(Buffer.from(text, "base64")) : Uint8Array.from(atob(text), (c) => c.charCodeAt(0)));

/** Decode \`data\` (a whole compressed stream) to exactly \`rawSize\` bytes. Returns a new Uint8Array. */
export const { decompress } = instantiate(decodeBase64(WASM_BASE64));
`;
mkdirSync(new URL("js/dist/", root), { recursive: true });
writeFileSync(new URL("js/dist/kraken-decode.mjs", root), out);
console.log(`js/dist/kraken-decode.mjs: ${out.length} bytes (wasm ${wasm.length})`);
